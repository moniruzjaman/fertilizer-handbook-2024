    fun findByAezNumber(number: Int): AezInfo? {
        return aezList.firstOrNull { it.aezNumber == number }
    }

    fun findNearestAez(latitude: Double, longitude: Double): AezInfo {
        return aezList.minByOrNull { aez ->
            distanceBetween(latitude, longitude, aez.centerLatitude, aez.centerLongitude)
        } ?: aezList.first()
    }

    fun findByDistrict(districtName: String): AezInfo? {
        val clean = districtName.trim().lowercase()
        return aezList.firstOrNull { aez ->
            aez.primaryDistricts.any { it.lowercase() == clean || clean.contains(it.lowercase()) }
        }
    }

    private fun distanceBetween(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0 // Earth radius in km
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2) * sin(dLat / 2) +
                cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) *
                sin(dLon / 2) * sin(dLon / 2)
        val c = 2 * atan2(sqrt(a), sqrt(1 - a))
        return r * c
    }
